export function detectWorkflowJsonFormat(rawJson) {
  if (!rawJson || !Array.isArray(rawJson.nodes)) return 'unknown';
  if (rawJson.nodes.some((n) => ['IMAGE_INPUT', 'FLOW_IMAGE_GEN', 'FLOW_VIDEO_GEN', 'FFMPEG_POST'].includes(n.type))) {
    return 'ai-canvas-studio';
  }
  if (
    rawJson.schema === 'soratk.workflow-template.v1' ||
    rawJson.nodes.some((n) => n.type === 'imageAssetNode' || n.type === 'imageNode' || n.type === 'videoNode')
  ) {
    return 'soratk.workflow-template.v1';
  }
  if (
    rawJson.type === 'newapi-canvas' ||
    rawJson.nodes.some((n) => n.position && n.data && ('current_output' in n.data || 'layout_version' in n.data))
  ) {
    return 'newapi-canvas';
  }
  return 'da-ai-canvas';
}

function normalizeToDaCanvasInput(rawJson) {
  const fmt = detectWorkflowJsonFormat(rawJson);

  if (fmt === 'soratk.workflow-template.v1') {
    const stickers = [];
    const nodes = [];
    const skippedIds = new Set();

    for (const n of rawJson.nodes) {
      const d = n.data || {};
      const t = String(n.type || '').toLowerCase();
      if (t.includes('text') || t.includes('vision') || t.includes('assistant')) {
        skippedIds.add(n.id);
        stickers.push({
          id: `sticker-${n.id}`,
          x: n.position?.x ?? n.x ?? 0,
          y: n.position?.y ?? n.y ?? 0,
          width: 280,
          height: 150,
          title: d.title || 'Note',
          html: `<p>${String(d.text || d.prompt || '').replace(/\n/g, '<br/>')}</p>`
        });
        continue;
      }
      const isVideo = t.includes('video');
      const mediaUrl = isVideo
        ? d.resultVideo || d.videoUrl || d.resultUrl || ''
        : d.resultImage || d.imageUrl || d.previewUrl || d.resultUrl || '';
      nodes.push({
        id: n.id,
        kind: isVideo ? 'video' : 'image',
        title: d.title || (isVideo ? 'AI Video' : 'AI Image'),
        x: n.position?.x ?? n.x ?? 0,
        y: n.position?.y ?? n.y ?? 0,
        meta: {
          mediaUrl,
          prompt: d.prompt || '',
          settings: {
            params: {
              ratio: d.ratio || (isVideo ? '16:9' : '9:16'),
              resolution: d.resolution || (isVideo ? '720p' : '1K'),
              duration: d.duration || '5s'
            }
          }
        }
      });
    }

    const edges = (rawJson.edges || [])
      .filter((e) => !skippedIds.has(e.source || e.from) && !skippedIds.has(e.target || e.to))
      .map((e) => ({
        id: e.id,
        from: e.source || e.from,
        to: e.target || e.to
      }));

    return { ...rawJson, nodes, edges, stickers: stickers.length > 0 ? stickers : rawJson.stickers };
  }

  if (fmt === 'newapi-canvas') {
    const stickers = [];
    const nodes = [];
    const skippedIds = new Set();

    for (const n of rawJson.nodes) {
      const d = n.data || {};
      if (n.type === 'text') {
        skippedIds.add(n.id);
        stickers.push({
          id: `sticker-${n.id}`,
          x: n.position?.x ?? n.x ?? 0,
          y: n.position?.y ?? n.y ?? 0,
          width: n.measured?.width || 250,
          height: n.measured?.height || 180,
          title: d.label || 'Note',
          html: `<p>${String(d.text || '').replace(/\n/g, '<br/>')}</p>`
        });
        continue;
      }
      const isVideo = n.type === 'video' || d.current_output?.media_type === 'video';
      const mediaUrl = d.current_output?.content_url || '';
      const params = d.params || {};
      nodes.push({
        id: n.id,
        kind: isVideo ? 'video' : 'image',
        title: d.label || (isVideo ? 'AI Video' : 'AI Image'),
        x: n.position?.x ?? n.x ?? 0,
        y: n.position?.y ?? n.y ?? 0,
        meta: {
          mediaUrl,
          prompt: d.prompt || '',
          dimensions: n.measured ? { width: n.measured.width, height: n.measured.height } : '',
          settings: {
            params: isVideo
              ? {
                  ratio: params['metadata.ratio'] || '16:9',
                  resolution: params['metadata.resolution'] || '720p',
                  duration: params.duration ? `${params.duration}s` : '5s'
                }
              : {
                  ratio: params.size || '9:16',
                  resolution: params['metadata.resolution'] ? String(params['metadata.resolution']).toUpperCase() : '1K'
                }
          }
        }
      });
    }

    const edges = (rawJson.edges || [])
      .filter((e) => !skippedIds.has(e.source || e.from) && !skippedIds.has(e.target || e.to))
      .map((e) => ({
        id: e.id,
        from: e.source || e.from,
        to: e.target || e.to
      }));

    return { ...rawJson, nodes, edges, stickers: stickers.length > 0 ? stickers : rawJson.stickers };
  }

  return rawJson;
}

/**
 * Hàm chuyển đổi JSON ("da-ai-canvas", "soratk.workflow-template.v1", "newapi-canvas" hoặc AI Canvas Studio) sang định dạng Project
 */
export function convertDaAiCanvasToProject(rawInput, options = {}) {
  if (!rawInput || !Array.isArray(rawInput.nodes)) {
    throw new Error('JSON không hợp lệ (thiếu danh sách nodes)!');
  }

  const opt = typeof options === 'string' ? { name: options } : options || {};
  const fmt = detectWorkflowJsonFormat(rawInput);

  if (fmt === 'ai-canvas-studio') {
    const convertedEdges = (Array.isArray(rawInput.edges) ? rawInput.edges : []).map((e) => ({
      id: e.id || `edge-${e.source || e.from}-${e.target || e.to}`,
      source: e.source || e.from,
      target: e.target || e.to
    }));
    return {
      ...rawInput,
      id: opt.id || rawInput.id || 'proj-imported-' + Date.now(),
      name: opt.name || rawInput.name || rawInput.title || 'Dự án nhập từ JSON',
      nodes: rawInput.nodes.map((n) => ({
        ...n,
        x: Math.round(Number(n.x ?? n.position?.x) || 40),
        y: Math.round(Number(n.y ?? n.position?.y) || 40),
        data: {
          status: n.data?.resultUrl || n.data?.imageUrl ? 'done' : 'idle',
          ...n.data
        }
      })),
      edges: convertedEdges,
      stickers: Array.isArray(rawInput.stickers) ? rawInput.stickers : []
    };
  }

  const rawJson = normalizeToDaCanvasInput(rawInput);

  const rawEdges = Array.isArray(rawJson.edges) ? rawJson.edges : [];
  const rawStickers =
    Array.isArray(rawJson.stickers) && rawJson.stickers.length > 0
      ? rawJson.stickers
      : Array.isArray(opt.stickers)
      ? opt.stickers
      : [];

  // Tìm minX, minY để chuẩn hóa tọa độ về gần gốc (40, 40) giúp mở dự án ra là thấy ngay toàn cảnh
  const allX = [
    ...rawJson.nodes.map((n) => Number(n.x) || 0),
    ...rawStickers.map((s) => Number(s.x) || 0)
  ];
  const allY = [
    ...rawJson.nodes.map((n) => Number(n.y) || 0),
    ...rawStickers.map((s) => Number(s.y) || 0)
  ];

  const minX = allX.length > 0 ? Math.min(...allX) : 0;
  const minY = allY.length > 0 ? Math.min(...allY) : 0;

  // Giãn trục Y (1.32x) và trục X (1.05x) để các thẻ Kính 310px chứa ảnh/video hiển thị thoáng đãng, không đè lên nhau
  const normX = (x) => Math.round((Number(x) - minX) * 1.05 + 40);
  const normY = (y) => Math.round((Number(y) - minY) * 1.32 + 40);

  const incomingTargetSet = new Set(rawEdges.map((e) => e.to || e.target));

  const convertedNodes = rawJson.nodes.map((n) => {
    const hasIncoming = incomingTargetSet.has(n.id);
    const meta = n.meta || {};
    const prompt = meta.prompt || n.data?.prompt || '';
    const mediaUrl = meta.mediaUrl || meta.originalMediaUrl || n.data?.resultUrl || n.data?.imageUrl || '';

    let type = n.type;
    if (!type) {
      if (n.kind === 'image') {
        type = hasIncoming ? 'FLOW_IMAGE_GEN' : mediaUrl ? 'IMAGE_INPUT' : prompt ? 'FLOW_IMAGE_GEN' : 'IMAGE_INPUT';
      } else if (n.kind === 'video') {
        // Nếu Node video không có prompt và không có dây nối vào (như node 冬季.mp4) hoặc là bản HD 1080p -> FFMPEG_POST
        if (!prompt && !hasIncoming) {
          type = 'FFMPEG_POST';
        } else {
          type = 'FLOW_VIDEO_GEN';
        }
      } else {
        type = 'FLOW_IMAGE_GEN';
      }
    }

    const ratio = meta?.settings?.params?.ratio || '9:16';
    const resolution = meta?.settings?.params?.resolution || '480p';
    const duration = meta?.settings?.params?.duration || '15';

    return {
      id: n.id,
      type,
      x: normX(n.x),
      y: normY(n.y),
      data: {
        title: n.title || 'Node',
        imageUrl: type === 'IMAGE_INPUT' ? mediaUrl : '',
        resultUrl: type !== 'IMAGE_INPUT' ? mediaUrl : '',
        fallbackUrl: type !== 'IMAGE_INPUT' ? mediaUrl : '',
        prompt,
        aspectRatio: ratio,
        resolution,
        duration,
        dimensions: meta.dimensions || '',
        targetResolution: '1080x1920',
        status: mediaUrl ? 'done' : 'idle'
      }
    };
  });

  const convertedEdges = rawEdges.map((e) => ({
    id: e.id || `edge-${e.from || e.source}-${e.to || e.target}`,
    source: e.from || e.source,
    target: e.to || e.target
  }));

  // Nếu có node FLOW_VIDEO_GEN và node FFMPEG_POST mà chưa nối dây giữa 2 cột cuối, tự động nối
  const vidGenNodes = convertedNodes.filter((n) => n.type === 'FLOW_VIDEO_GEN');
  const postNodes = convertedNodes.filter((n) => n.type === 'FFMPEG_POST');
  if (vidGenNodes.length === 1 && postNodes.length === 1) {
    const vId = vidGenNodes[0].id;
    const pId = postNodes[0].id;
    const alreadyConnected = convertedEdges.some((e) => e.source === vId && e.target === pId);
    if (!alreadyConnected) {
      convertedEdges.push({
        id: `edge-auto-${vId}-${pId}`,
        source: vId,
        target: pId
      });
    }
  }

  const convertedStickers = rawStickers.map((s) => ({
    id: s.id || 'sticker-' + Date.now() + Math.random(),
    x: normX(s.x),
    y: normY(s.y),
    width: Math.round(Number(s.width) || 280),
    height: Math.round(Number(s.height) || 140),
    title: s.title || 'Note (Ghi chú)',
    html: s.html || ''
  }));

  return {
    id: opt.id || rawJson.id || 'proj-winter-velvet-luxe-fur',
    category: opt.category || 'video',
    name:
      opt.name ||
      'Winter Velvet & Luxe Fur — Lookbook 4 Bộ Lông Thú & Video Stop-Motion 15s (da-ai-canvas)',
    description:
      opt.description ||
      'Dự án chuẩn da-ai-canvas v2: 1 Ảnh Mẫu 3 góc độ + 4 Bộ trang phục lông thú → 4 Nhánh thay đồ 3 góc độ → Video 480p góc chụp 90° Top-Down Sofa → Video HD 1080×1920 (冬季.mp4) kèm đầy đủ 5 Ghi chú (Stickers).',
    badge: opt.badge || 'Dự Án Thực Tế (Full Media)',
    techTag: opt.techTag || 'DA-V2',
    workspaceMode: opt.workspaceMode || 'workflow',
    previewVideo: opt.previewVideo || '',
    previewImage: opt.previewImage || '',
    nodes: convertedNodes,
    edges: convertedEdges,
    stickers: convertedStickers,
    updatedAt: new Date().toISOString()
  };
}

